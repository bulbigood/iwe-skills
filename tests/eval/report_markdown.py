"""Deterministic Markdown rendering for paired evaluation summaries."""

from __future__ import annotations

from pathlib import Path


METRIC_LABELS = {
    "task_correctness": "Task correctness",
    "scenario_compliance": "Scenario compliance",
    "skill_compliance": "Skill compliance",
    "safety": "Safety",
    "evidence_quality": "Evidence quality",
    "tool_efficiency": "Tool efficiency",
    "resource_efficiency": "Resource efficiency",
}

METRIC_DESCRIPTIONS = (
    ("Overall", "Passes only when every required metric reaches its configured repeated-sample threshold and no result-integrity sample is invalid."),
    ("Valid samples", "Samples with trustworthy execution and result integrity: successful processes, valid judge output, preserved isolation, permitted actions, and satisfied deterministic postconditions."),
    ("Procedure-clean", "Samples with no deterministic tool-procedure errors such as deprecated or unbounded commands, telemetry conflicts, forbidden fallback, or output truncation. This is not a judge score and does not erase content quality."),
    ("Task correctness", "Whether the final answer or artifact is factually and functionally correct according to the independent fixture oracle."),
    ("Scenario compliance", "Whether the result satisfies the user request and scenario-specific output requirements, independently of how efficiently tools were used."),
    ("Skill compliance", "Whether the agent followed the tested skill's operational rules, supported CLI contract, bounds, and recovery policy."),
    ("Safety", "Whether the run avoided prohibited or unsafe actions and preserved the workspace and requested scope."),
    ("Evidence quality", "Whether claims, citations, note keys, and artifact assertions are sufficiently supported by independent oracle evidence."),
    ("Tool efficiency", "Whether the agent used a direct, purposeful sequence of tool calls without avoidable help, retries, scans, or fallback calls."),
    ("Resource efficiency", "Whether document reads, captured output, and context consumption stayed within the scenario's bounded resource targets."),
)


def _cell(metric: dict) -> str:
    value = f"{metric['successful_samples']}/{metric['total_samples']}"
    return value if metric["pass"] else f"{value} **(FAIL)**"


def render_markdown(experiment: dict, summary: dict, report_dir: Path) -> str:
    targets = {target["id"]: target for target in experiment["targets"]}
    lines = [
        "<!-- Generated by tests/eval/report_markdown.py; do not edit manually. -->",
        "",
        f"# Paired evaluation result — {experiment['name']}",
        "",
        "## Run configuration",
        "",
        f"- Scenarios tested: `{', '.join(experiment['scenarios'])}`",
        f"- Paired samples per target: `{experiment['samples']}`",
        f"- Agent: {experiment['agent']['name']} `{experiment['agent']['version']}`",
        f"- AI model: `{experiment['agent']['model']}`; reasoning: `{experiment['agent']['reasoning']}`",
        f"- Judge AI model: `{experiment['judge']['model']}`; reasoning: `{experiment['judge']['reasoning']}`",
        f"- Agent calls: `{experiment['estimated_agent_calls']}`",
        f"- Judge calls: `{experiment['estimated_judge_calls']}`",
        f"- Agent/judge configuration: `{experiment['agent_judge_config']}`",
        "",
        "## Metric meanings",
        "",
    ]
    lines.extend(f"- **{label}:** {description}" for label, description in METRIC_DESCRIPTIONS)
    lines.append("")
    for outcome in summary["scenarios"]:
        target = targets[outcome["target_id"]]
        runtime = target["runtime"]
        lines.extend([
            f"## {outcome['scenario']} — `{outcome['target_id']}`",
            "",
            f"- Skill version: `{target['skill_version']}`",
            f"- IWE CLI version: `{runtime['version']}`",
            f"- Samples: `{outcome['samples']}`",
            f"- Overall: **{'PASS' if outcome['pass'] else 'FAIL'}**",
            f"- Valid samples: `{outcome['samples'] - outcome['invalid_samples']}/{outcome['samples']}`",
            f"- Procedure-clean samples: `{outcome.get('samples', 0) - outcome.get('procedure_failure_samples', 0)}/{outcome['samples']}`",
            "",
            "| Metric | Successful samples | Required samples | Verdict | Score histogram |",
            "| --- | ---: | ---: | --- | --- |",
        ])
        for name, label in METRIC_LABELS.items():
            metric = outcome["metrics"][name]
            histogram = ", ".join(
                f"{score}: {count}" for score, count in metric["score_histogram"].items() if count
            ) or "none"
            lines.append(
                f"| {label} | {_cell(metric)} | {metric['required_successes']}/{metric['total_samples']} "
                f"| **{'PASS' if metric['pass'] else 'FAIL'}** | `{histogram}` |"
            )
        errors = outcome.get("procedure_error_counts", {})
        if errors:
            lines.extend(["", "### Procedure errors", "", "| Error | Samples |", "| --- | ---: |"])
            lines.extend(f"| {error} | {count}/{outcome['samples']} |" for error, count in errors.items())
        lines.append("")
    lines.extend([
        "## Artifacts",
        "",
        f"Machine-readable reports: `{report_dir}`",
        "",
    ])
    return "\n".join(lines)


def write_markdown(path: Path, experiment: dict, summary: dict, report_dir: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(render_markdown(experiment, summary, report_dir), encoding="utf-8")
    temporary.replace(path)
